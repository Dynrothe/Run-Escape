// Random picks before a number goes on the end: with these lists that's only
// once thousands of names are in use at once
const TRIES = 32;

function pick(words, random) {
    return words[random(words.length)];
}

// A name from these words that isn't taken: two of them, and a number after
// if every pair tried was. random(n) gives 0 to n - 1.
export function readableName(adjectives, nouns, taken = () => false, random = randomInt) {
    for (let i = 0; i < TRIES; i++) {
        const name = `${pick(adjectives, random)} ${pick(nouns, random)}`;
        if (!taken(name)) {
            return name;
        }
    }
    for (let number = 2; ; number++) {
        const name = `${pick(adjectives, random)} ${pick(nouns, random)} ${number}`;
        if (!taken(name)) {
            return name;
        }
    }
}

export function playerName(taken, random) {
    return readableName(PLAYER_ADJECTIVES, PLAYER_NOUNS, taken, random);
}

export function roomName(taken, random) {
    return readableName(ROOM_ADJECTIVES, ROOM_NOUNS, taken, random);
}

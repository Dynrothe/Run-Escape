// The hilt sets a godsword's special attack
function godsword(
    id: string,
    name: string,
    objId: number,
    description: string,
    special: SpecialAttackDef,
): WeaponDef {
    return {
        id,
        name,
        kind: "sweep",
        description: `A heavy two-handed sweep. ${description}`,
        iconObjId: objId,
        playerSeq: GODSWORD_SEQ,
        sound: GODSWORD_SOUND,
        hitSound: -1,
        rarity: "rare",
        style: "melee",
        family: "godsword",
        special,
        levels: godswordLevels(objId),
    };
}


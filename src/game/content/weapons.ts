export const WEAPON_BY_ID: Map<string, WeaponDef> = new Map(WEAPONS.map((w) => [w.id, w]));

export function getWeapon(id: string): WeaponDef {
    const weapon = WEAPON_BY_ID.get(id);
    if (!weapon) {
        throw new Error("Unknown weapon " + id);
    }
    return weapon;
}

// The style a weapon's hits count as (see WeaponDef.damageStyle)
export function getWeaponStyle(weapon: WeaponDef): CombatStyle {
    const style = weapon.damageStyle ?? weapon.style;
    if (style) {
        return style;
    }
    switch (weapon.kind) {
        case "slash":
        case "sweep":
            return "melee";
        case "missile":
        case "knives":
        case "axes":
            return "ranged";
        case "aura":
        case "strike":
        case "orbit":
            return "magic";
    }
}
